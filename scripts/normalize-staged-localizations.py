#!/usr/bin/env python3
"""Normalize catalog blobs without staging unrelated working-tree edits."""

import json
from pathlib import Path
import re
import subprocess


def git(*args, data=None):
    return subprocess.run(["git", *args], input=data, capture_output=True, check=True).stdout


def main():
    names = git("diff", "--cached", "--name-only", "--diff-filter=ACM", "-z", "--", "*.xcstrings")
    for raw_name in names.split(b"\0"):
        if not raw_name:
            continue
        name = raw_name.decode("utf-8")
        entry = git("ls-files", "--stage", "-z", "--", name).split(b"\t", 1)[0]
        mode, oid, stage = entry.split()
        if mode not in (b"100644", b"100755") or stage != b"0":
            raise ValueError("Cannot normalize a non-regular or conflicted catalog")
        original = git("cat-file", "blob", oid.decode())
        updated = re.sub(
            rb'^[ \t]*"comment"\s*:\s*[^\n]*,\n^[ \t]*"isCommentAutoGenerated"\s*:\s*true,?\n',
            b"", original, flags=re.MULTILINE,
        )
        json.loads(updated)
        if updated == original:
            continue
        new_oid = git("hash-object", "-w", "--stdin", data=updated).strip()
        git("update-index", "-z", "--index-info", data=mode + b" " + new_oid + b"\t" + raw_name + b"\0")
        path = Path(name)
        if not path.is_symlink() and path.is_file() and path.read_bytes() == original:
            path.write_bytes(updated)


if __name__ == "__main__":
    main()
