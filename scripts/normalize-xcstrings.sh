#!/usr/bin/env bash
set -euo pipefail

if [[ $# -eq 0 ]]; then
  echo "usage: $0 <path/to/file.xcstrings> [more-files...]" >&2
  exit 1
fi

for file_path in "$@"; do
  if [[ ! -f "$file_path" ]]; then
    continue
  fi

  temp_file="$(mktemp)"
  perl -0pe '
    s/^[ \t]*"comment"\s*:\s*[^\n]*,\n^[ \t]*"isCommentAutoGenerated"\s*:\s*true,?\n//mg
  ' "$file_path" > "$temp_file"

  if ! cmp -s "$file_path" "$temp_file"; then
    mv "$temp_file" "$file_path"
  else
    rm -f "$temp_file"
  fi
done
