"""Illustrative fund prices for Portfolio Lab's sample mode.

These closes are synthetic. They are generated, not downloaded, so the app
can ship them without any data license, and they must always be labeled as
illustrative. They line up with the months of the published FX snapshot.
"""

from __future__ import annotations

import numpy as np

FUNDS = [
    # symbol, name, currency, kind, annual drift, annual volatility, market exposure
    ("VTI", "US total stock market", "USD", "equity", 0.085, 0.16, 1.0),
    ("VXUS", "International stocks", "USD", "equity", 0.060, 0.15, 0.8),
    ("BND", "US bonds", "USD", "bond", 0.025, 0.05, 0.1),
    ("XIC", "Canadian stocks", "CAD", "equity", 0.070, 0.14, 0.7),
    ("ZAG", "Canadian bonds", "CAD", "bond", 0.025, 0.05, 0.1),
]
NOTE = ("Illustrative prices generated by NomadFi for teaching. They are not real fund prices "
        "and say nothing about future returns.")


def sample_market(months: list[str], seed: int = 2026) -> dict:
    rng = np.random.default_rng(seed)
    market = rng.normal(0, 0.04, len(months))
    series = []
    for symbol, name, currency, kind, drift, volatility, exposure in FUNDS:
        own = np.sqrt(max(volatility**2 / 12 - (exposure * 0.04) ** 2, 1e-6))
        monthly = drift / 12 + exposure * market + rng.normal(0, own, len(months))
        monthly[0] = 0.0
        closes = 100 * np.cumprod(1 + monthly)
        series.append({
            "asset": {"symbol": symbol, "name": name, "currency": currency, "kind": kind},
            "closes": [{"month": m, "close": round(float(c), 4)} for m, c in zip(months, closes)],
        })
    return {"schemaVersion": 1, "illustrative": True, "note": NOTE, "series": series}
