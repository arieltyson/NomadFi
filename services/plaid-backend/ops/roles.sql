CREATE ROLE nomadfi_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE ROLE nomadfi_fibot NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
